"""Validation helpers that check LabIMotion structures against their JSON schemas.

The schemas bundled here are a client-side reimplementation of what the server accepts
(LabIMotion serves no schema documents over its API). They track **LabIMotion 2.1.1 as
shipped with Chemotion ELN v3.1.2** — when connecting to an instance on another version,
use :meth:`chemotion_api.labImotion.GenericManager.check_schema_drift` to verify the
instance's klasses still conform before editing or uploading templates.

Importing this package registers every schema with :class:`SchemaRegistry`. Running it as a
script regenerates ``schemas/imports.py`` from the ``schema_*.py`` modules on disk.
"""

import os

# Side-effect import: registers every schema with SchemaRegistry (see schemas/imports.py).
import chemotion_api.labImotion.items.validation.schemas.imports  # noqa: F401
from chemotion_api.labImotion.items.validation.registry import SchemaRegistry
from chemotion_api.utils import resource_path


if __name__ == '__main__':
    A = [
        '"""Side-effect imports: importing this module registers every schema with SchemaRegistry.',
        '',
        'This file is regenerated by running ``chemotion_api.labImotion.items.validation`` as a script.',
        '"""',
        '',
    ]
    for module in sorted(os.listdir(os.path.join(resource_path(__file__), 'schemas'))):
        if module.startswith('schema_') and module[-3:] == '.py':
            # noqa marker: these imports exist purely for their side effect (schema registration)
            A.append(f'import chemotion_api.labImotion.items.validation.schemas.{module[:-3]}  # noqa: F401')

    with open(os.path.join(resource_path(__file__), 'schemas/imports.py'), 'w') as f:
        f.write('\n'.join(A) + '\n')
    exit()


def validate_selection_options(json_to_test: dict):
    """Validate a select-options map against the generic select-option schema.

    :param json_to_test: The select-options dictionary to validate.
    :raises jsonschema.ValidationError: If ``json_to_test`` does not match the schema.
    """
    validator = SchemaRegistry.instance().validator_for('chemotion://generic/select_option/draft-01')
    validator.validate(json_to_test)


